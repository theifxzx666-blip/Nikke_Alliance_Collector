def to_simple(text: str) -> str:
    """把字符串里的常见繁体字换成简体，用于比较。查不到的字原样保留。"""
    if not text:
        return text or ""
    return "".join(_TRAD.get(ch, ch) for ch in text)


def same_word(a: str, b: str) -> bool:
    """繁简归一后是不是同一个字串。"""
    return bool(a) and bool(b) and to_simple(a) == to_simple(b)
